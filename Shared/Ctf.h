#pragma once

#include <stdint.h>

// Capture the flag: what the server and the client both need to know about
// the match and the map. The rules themselves are in Server/Ctf.c.

#define RR_CTF_MAX_TEAMS 4
#define RR_CTF_QUADRANT_COUNT 4
#define RR_CTF_FLAGS_PER_TEAM 3
// the map is generated by tools/ctf/gen-map.js, this is its size in template
// cells (each one is two maze cells wide)
#define RR_CTF_TEMPLATE_DIM 79

// the server ticks 25 times a second
#define RR_CTF_TPS 25
// phase lengths, in seconds. The sealed phase is how long the walls stay up.
#define RR_CTF_PLACEMENT_SECONDS 60
#define RR_CTF_FARM_SECONDS 600
#define RR_CTF_ENDED_SECONDS 20
// a dead player is put back at their base after this many ticks
#define RR_CTF_RESPAWN_TICKS 25
// a team holding fewer flags than this is out
#define RR_CTF_MIN_FLAGS 3
// how close a player has to be, in world units, to grab a flag, to bank one at
// a flag point, and to set one up on an empty flag point
#define RR_CTF_PICKUP_RADIUS 90.0f
#define RR_CTF_BANK_RADIUS 130.0f
#define RR_CTF_SETUP_RADIUS 130.0f
#define RR_CTF_SETUP_TICKS (3 * RR_CTF_TPS)
// a dropped flag goes home after this long if nobody picks it up
#define RR_CTF_RETURN_TICKS (15 * RR_CTF_TPS)
// flag points of one team have to be at least this far apart
#define RR_CTF_POINT_SPACING 800.0f
// how many recent events the state packet carries, for the banners
#define RR_CTF_EVENT_HISTORY 4

enum rr_ctf_phase
{
    rr_ctf_phase_lobby,     // squads are linked, waiting for the host
    rr_ctf_phase_placement, // leaders place their flag points
    rr_ctf_phase_farm,      // walls up, farm mobs and craft
    rr_ctf_phase_war,       // walls down, take the flags
    rr_ctf_phase_ended
};

enum rr_ctf_flag_state
{
    rr_ctf_flag_standing, // on a flag point
    rr_ctf_flag_carried,  // a player has it
    rr_ctf_flag_dropped,  // on the ground, goes home when the timer runs out
    rr_ctf_flag_banked    // safe in a team's bank
};

// what happened, shown as a banner. a, b and flag depend on the type
enum rr_ctf_event_type
{
    rr_ctf_event_none,
    rr_ctf_event_taken,      // a = team that took it, b = team it came from
    rr_ctf_event_banked,     // a = team that banked it, b = team it came from
    rr_ctf_event_dropped,    // a = team that held it, b = team that lost it
    rr_ctf_event_returned,   // a = team it went back to
    rr_ctf_event_setup,      // a = team that set it up
    rr_ctf_event_eliminated, // a = team that is out, b = team that did it
    rr_ctf_event_won,        // a = the winner
    rr_ctf_event_walls       // the walls dropped
};

// the host's feedback, shown on the host panel
enum rr_ctf_message
{
    rr_ctf_message_none,
    rr_ctf_message_linked,      // arg = number of teams
    rr_ctf_message_bad_code,    // arg = which code (1 is the first)
    rr_ctf_message_not_private, // arg = which code
    rr_ctf_message_same_squad,  // arg = which code
    rr_ctf_message_not_host,
    rr_ctf_message_need_teams,
    rr_ctf_message_empty_team,
    rr_ctf_message_busy,        // another host already linked squads, or a match runs
    rr_ctf_message_not_leader,
    rr_ctf_message_bad_spot,    // a flag point can't go there
    rr_ctf_message_too_close,   // too close to another flag point
    rr_ctf_message_not_member,  // a player outside the match tried to join
    rr_ctf_message_cancelled
};

// a rectangle of template cells
struct rr_ctf_rect
{
    uint8_t x;
    uint8_t y;
    uint8_t w;
    uint8_t h;
};

// one of the walls between the team areas, and what it turns into when the
// walls drop (the difficulty letter of the ground next to it)
struct rr_ctf_seam_cell
{
    uint8_t x;
    uint8_t y;
    uint8_t value;
};

// the four team areas, their spawn rectangles and the flags a team gets if its
// leader does not place them. All in template cells.
extern struct rr_ctf_rect RR_CTF_QUADRANTS[RR_CTF_QUADRANT_COUNT];
extern struct rr_ctf_rect RR_CTF_SPAWNS[RR_CTF_QUADRANT_COUNT];
extern uint8_t RR_CTF_DEFAULT_FLAGS[RR_CTF_QUADRANT_COUNT][RR_CTF_FLAGS_PER_TEAM][2];
extern struct rr_ctf_seam_cell RR_CTF_SEAM_CELLS[];
extern uint16_t RR_CTF_SEAM_COUNT;

// which area a team plays in, so that two teams start in opposite corners
uint8_t rr_ctf_team_quadrant(uint8_t team);
// the team colours, 0xAARRGGBB, red blue green yellow
uint32_t rr_ctf_team_color(uint8_t team);
char const *rr_ctf_team_name(uint8_t team);

// width of one template cell in world units
float rr_ctf_cell_size();
// opens the walls between the team areas. Safe to call more than once, the
// server and every client call it so their maps agree
void rr_ctf_drop_walls();
// walls back to what the map file says, for the start of the next match
void rr_ctf_reset_walls();
uint8_t rr_ctf_walls_dropped();
